import { z } from 'zod';

const DIRECT_UPLOAD_MAX_BYTES = 10 * 1024 * 1024;
const DIRECT_UPLOAD_MAX_BASE64_CHARS = Math.ceil(DIRECT_UPLOAD_MAX_BYTES / 3) * 4;

export const AttachFileInput = z
  .object({
    issue_id: z.union([z.string().min(1), z.number().int().positive()]),
    project: z.string().min(1).max(255).optional(),
    filename: z.string().min(1).max(255),
    mime_type: z.string().min(1).max(127),
    size: z.number().int().positive(),
    complete: z.boolean().optional(),
    object_key: z.string().min(1).max(1024).optional(),
    content_base64: z.string().min(1).max(DIRECT_UPLOAD_MAX_BASE64_CHARS).optional(),
  })
  .superRefine((value, ctx) => {
    if (value.content_base64 && value.object_key) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'object_key is generated by attach_file when content_base64 is provided',
        path: ['object_key'],
      });
    }
    if (value.content_base64 && value.complete) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'complete is implied when content_base64 is provided',
        path: ['complete'],
      });
    }
    if (value.complete && !value.object_key && !value.content_base64) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'object_key is required when complete=true',
        path: ['object_key'],
      });
    }
  });

export type AttachFileInput = z.infer<typeof AttachFileInput>;
